def add_heading_ar(text, level=1):
    h = doc.add_heading(text, level=level)
    h.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    return h

def add_para_ar(text, bold=False):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = p.add_run(text)
    run.font.name = 'Arial'
    run.font.size = Pt(11)
    if bold:
        run.bold = True
    return p

def add_bullet_ar(text):
    p = doc.add_paragraph(style='List Bullet')
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    run = p.add_run(text)
    run.font.name = 'Arial'
    run.font.size = Pt(11)
    return p

def add_table_ar(headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = 'Table Grid'
    table.alignment = WD_TABLE_ALIGNMENT.RIGHT
    # headers
    hdr = table.rows[0].cells
    for i,h in enumerate(headers):
        hdr[i].text = h
        for p in hdr[i].paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            for r in p.runs:
                r.bold = True
                r.font.name = 'Arial'
                r.font.size = Pt(10)
    # rows
    for r in range(len(rows)):
        cells = table.rows[r+1].cells
        for c in range(len(headers)):
            val = rows[r][c] if c < len(rows[r]) else ''
            cells[c].text = val
            for p in cells[c].paragraphs:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
                for rr in p.runs:
                    rr.font.name = 'Arial'
                    rr.font.size = Pt(10)
    return table

