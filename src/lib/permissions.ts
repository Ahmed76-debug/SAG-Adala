export function rolePermissions(role: Role): Permission[] {
  return ROLE_PERMISSIONS[role] ?? [];
}

export function can(
  user: { role: Role; permOverrides?: Partial<Record<Permission, boolean>> } | null | undefined,
  perm: Permission,
): boolean {
  if (!user) return false;
  const override = user.permOverrides?.[perm];
  if (typeof override === "boolean") return override;
  return rolePermissions(user.role).includes(perm);
}

export function canAny(
  user: Parameters<typeof can>[0],
  perms: Permission[],
): boolean {
  return perms.some((p) => can(user, p));
}
